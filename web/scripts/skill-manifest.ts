#!/usr/bin/env bun
// Generate / check `packs/skills/skills-manifest.json` (spec `uiux-agent-enrichment.md`
// AC2.2–AC2.4, PLAN Task 5 — ritchie B1).
//
// Inputs, all in packs/skills:
//   - `pack.json`        — hand-maintained: every top-level entry, its kind, origin
//                          (first-party | vendored) and Claude/Codex flag,
//   - `vendor-lock.json` — for vendored entries: upstream, licence, approval,
//                          knownIssues (reused, never duplicated by hand),
//   - the tree itself    — per-file sha256.
//
// Ship gate (fail closed): a vendored entry ships only if `vendored-skills` would
// pass it (licence shippable, bytes match the lock, review approved for these bytes)
// AND its knownIssues list is empty. A first-party entry ships if the repo licence is
// shippable. Blocked entries stay in the manifest with their reasons, so the package
// build can say what it left out and why (AC2.4).
//
// `generate` writes the manifest (tmp + rename); `check` fails when the committed
// manifest differs from what the tree produces, or on any structural error.

import { readdirSync, readFileSync, renameSync, statSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

import {
  filesDigest,
  frontmatterName,
  hashTree,
  invocationNames,
  OWNER_MARKER_FILE,
  packNameErrors,
  readTree,
  SKILL_MANIFEST_SCHEMA_VERSION,
  type ManifestEntry,
  type SkillManifest,
} from "../server/skill-manifest.js";
import { SHIPPABLE_CODE_LICENCES } from "./licences.js";
import { checkSkill, loadLock, PACK_SKILLS_DIR, VENDOR_LOCK_FILE, type VendorLock } from "./vendored-skills.js";

export const PACK_FILE = join(PACK_SKILLS_DIR, "pack.json");
export const MANIFEST_FILE = join(PACK_SKILLS_DIR, "skills-manifest.json");
const REPO_ROOT = resolve(PACK_SKILLS_DIR, "..", "..");

/** Files allowed at the packs/skills root; any other root file is an error, not a silent extra. */
export const ROOT_FILES: ReadonlySet<string> = new Set([
  "README.md",
  "THIRD_PARTY_NOTICES.md",
  "vendor-lock.json",
  "pack.json",
  "skills-manifest.json",
]);

/**
 * Dev-only files that never ship (PLAN Task 9). Matched on whole path segments, so
 * `references/tests-guide.md` ships and `scripts/tests/x.py` does not. The manifest
 * hashes exactly what is left (B1 decision 7): installPack copies, and ownership()
 * proves, that set and nothing else.
 */
const EXCLUDED_SEGMENTS: ReadonlyArray<[string, string]> = [
  [".git", "VCS metadata"],
  [".verify", "catalog canary scripts (CI-only)"],
  ["evals", "evaluation briefs (dev-only)"],
  ["tests", "upstream test suite (dev-only)"],
  ["__tests__", "test suite (dev-only)"],
  ["__fixtures__", "test fixtures (dev-only)"],
  ["fixtures", "test fixtures (dev-only)"],
];
const EXCLUDED_BASENAMES: ReadonlyMap<string, string> = new Map([[".gitignore", "VCS metadata"]]);
/** Excluded-dir files that are runtime data: selection-engine.md tells the Chair to read the vocabulary. */
const KEPT_PATHS: ReadonlySet<string> = new Set([".verify/capability-vocabulary.json"]);

/** Why `relPath` (inside an entry) is left out of the package, or null when it ships. */
export function excludedReason(relPath: string): string | null {
  if (KEPT_PATHS.has(relPath)) return null;
  const segs = relPath.split("/");
  const base = EXCLUDED_BASENAMES.get(segs[segs.length - 1]);
  if (base) return base;
  for (const [seg, reason] of EXCLUDED_SEGMENTS) if (segs.slice(0, -1).includes(seg)) return reason;
  return null;
}

export interface ExcludedFile {
  entry: string;
  path: string;
  reason: string;
}

const MANIFEST_DOC =
  "GENERATED by `cd web && bun scripts/skill-manifest.ts generate` from pack.json + vendor-lock.json + the tree; do not edit. Lists every entry packs/skills ships, with source, licence verdict, Claude/Codex flag, ship gate and per-file sha256. ship.status=blocked entries never ship. A copy Aura places carries .aura-owned.json; see web/server/skill-manifest.ts for the ownership rule.";

export interface PackEntry {
  name: string;
  kind: "skill" | "catalog";
  origin: "first-party" | "vendored";
  compat: { claude: boolean; codex: boolean; note?: string };
}

export interface PackDecl {
  _doc: string;
  schemaVersion: 1;
  firstParty: { repo: string; licence: string; licenceFile: string };
  entries: PackEntry[];
}

export interface ManifestInput {
  pack: PackDecl;
  lock: VendorLock;
  /** Top-level dirs and files actually present in packs/skills. */
  rootDirs: string[];
  rootFiles: string[];
  /** Each declared, present entry's files. */
  trees: Map<string, Map<string, Buffer>>;
  /** Text of the repo licence file named by pack.firstParty.licenceFile (null if missing). */
  repoLicenceText: string | null;
}

// ─── Pure core ──────────────────────────────────────────────────────────────

/** Re-exported: the server's skill-pack module needs the same parse (scripts/ does not ship). */
export { frontmatterName };

/** First-party licence verdict: shippable SPDX id AND the repo licence file says so. */
function firstPartyLicence(pack: PackDecl, text: string | null): { verdict: ManifestEntry["licence"]["verdict"]; reasons: string[] } {
  const spdx = pack.firstParty.licence;
  const reasons: string[] = [];
  if (!SHIPPABLE_CODE_LICENCES.has(spdx)) reasons.push(`repo licence ${spdx} is not shippable`);
  if (text === null) reasons.push(`repo licence file ${pack.firstParty.licenceFile} is missing`);
  else if (!text.startsWith(`${spdx} License`)) reasons.push(`repo licence file does not start with "${spdx} License"`);
  return { verdict: reasons.length ? "not-shippable" : "shippable", reasons };
}

/** Build the manifest. `errors` are structural (the manifest cannot be trusted); blocked entries are not errors. */
export function buildManifest(input: ManifestInput): { manifest: SkillManifest; errors: string[]; excluded: ExcludedFile[] } {
  const { pack, lock, trees } = input;
  const errors: string[] = [];
  const excluded: ExcludedFile[] = [];
  const declared = new Set(pack.entries.map((e) => e.name));
  const locked = new Map(lock.skills.map((s) => [s.name, s]));

  for (const d of input.rootDirs) if (!declared.has(d)) errors.push(`${d}/ is in packs/skills but not declared in pack.json`);
  for (const f of input.rootFiles) if (!ROOT_FILES.has(f)) errors.push(`${f} at the packs/skills root is not an allowed root file`);
  for (const s of lock.skills) {
    const e = pack.entries.find((x) => x.name === s.name);
    if (!e || e.origin !== "vendored") errors.push(`${s.name} is in vendor-lock.json but not declared as vendored in pack.json`);
  }

  const fp = firstPartyLicence(pack, input.repoLicenceText);
  const entries: ManifestEntry[] = [];
  for (const decl of [...pack.entries].sort((a, b) => (a.name < b.name ? -1 : 1))) {
    const n = decl.name;
    const tree = trees.get(n);
    if (!input.rootDirs.includes(n) || !tree) {
      errors.push(`${n} is declared in pack.json but packs/skills/${n}/ does not exist`);
      continue;
    }
    if ((!decl.compat.claude || !decl.compat.codex) && !decl.compat.note) errors.push(`${n}: compat has a false flag but no note saying why`);
    if (tree.has(OWNER_MARKER_FILE)) errors.push(`${n}: ${OWNER_MARKER_FILE} must never be committed into the pack`);
    const skillMd = tree.get("SKILL.md");
    if (decl.kind === "skill" && !skillMd) errors.push(`${n}: kind skill but no SKILL.md`);
    const fmName = skillMd ? frontmatterName(skillMd.toString("utf8")) : null;

    const shipped = new Map<string, Buffer>();
    for (const [p, b] of [...tree].sort(([a], [z]) => (a < z ? -1 : 1))) {
      const reason = excludedReason(p);
      if (reason) excluded.push({ entry: n, path: p, reason });
      else shipped.set(p, b);
    }
    if (shipped.size === 0) errors.push(`${n}: every file is excluded from the package`);
    const files = hashTree(shipped);
    let source: ManifestEntry["source"];
    let licence: ManifestEntry["licence"];
    const reasons: string[] = [];
    if (decl.origin === "vendored") {
      const s = locked.get(n);
      if (!s) {
        errors.push(`${n} is declared vendored but has no vendor-lock.json entry`);
        continue;
      }
      source = { type: "vendored", repo: s.upstream.repo, path: s.upstream.path, commit: s.upstream.commit };
      licence = { spdx: s.licence.spdx, verdict: SHIPPABLE_CODE_LICENCES.has(s.licence.spdx) ? "shippable" : "not-shippable" };
      reasons.push(...checkSkill(s, tree).map((e) => e.replace(`${n}: `, "")));
      reasons.push(...(s.knownIssues ?? []).map((i) => `known issue: ${i}`));
    } else {
      source = { type: "first-party", repo: pack.firstParty.repo };
      licence = { spdx: pack.firstParty.licence, verdict: fp.verdict };
      reasons.push(...fp.reasons);
    }
    entries.push({
      name: n,
      frontmatterName: fmName && fmName !== n ? fmName : null,
      kind: decl.kind,
      source,
      licence,
      compat: decl.compat,
      ship: { status: reasons.length ? "blocked" : "ship", reasons },
      digest: filesDigest(files),
      files,
    });
  }
  errors.push(...packNameErrors(entries.flatMap(invocationNames)));
  return { manifest: { _doc: MANIFEST_DOC, schemaVersion: SKILL_MANIFEST_SCHEMA_VERSION, entries }, errors, excluded };
}

export function serialiseManifest(m: SkillManifest): string {
  return JSON.stringify(m, null, 2) + "\n";
}

// ─── Effect shell ───────────────────────────────────────────────────────────

export function readInput(root = PACK_SKILLS_DIR): { input: ManifestInput; skipped: string[] } {
  const pack = JSON.parse(readFileSync(join(root, "pack.json"), "utf8")) as PackDecl;
  const lock = loadLock(join(root, "vendor-lock.json"));
  const rootDirs: string[] = [];
  const rootFiles: string[] = [];
  for (const name of readdirSync(root).sort()) (statSync(join(root, name)).isDirectory() ? rootDirs : rootFiles).push(name);
  const skipped: string[] = [];
  const trees = new Map<string, Map<string, Buffer>>();
  for (const e of pack.entries) {
    if (!rootDirs.includes(e.name)) continue;
    const s: string[] = [];
    trees.set(e.name, readTree(join(root, e.name), s));
    skipped.push(...s.map((p) => `${e.name}/${p}`));
  }
  let repoLicenceText: string | null = null;
  try {
    repoLicenceText = readFileSync(join(REPO_ROOT, pack.firstParty.licenceFile), "utf8");
  } catch {
    repoLicenceText = null;
  }
  return { input: { pack, lock, rootDirs, rootFiles, trees, repoLicenceText }, skipped };
}

function report(m: SkillManifest, excluded: ExcludedFile[]): void {
  const ship = m.entries.filter((e) => e.ship.status === "ship").map((e) => e.name);
  console.log(`skills manifest: ${m.entries.length} entries; ship: ${ship.join(", ") || "none"}`);
  const byReason = new Map<string, number>();
  for (const x of excluded) byReason.set(x.reason, (byReason.get(x.reason) ?? 0) + 1);
  for (const [reason, count] of byReason) console.log(`  excluded ${count} file(s): ${reason}`);
  for (const e of m.entries.filter((x) => x.ship.status === "blocked")) {
    console.log(`  blocked ${e.name}:\n    - ${e.ship.reasons.join("\n    - ")}`);
  }
}

function build(): { m: SkillManifest; excluded: ExcludedFile[] } | null {
  const { input, skipped } = readInput();
  for (const d of skipped) console.warn(`not hashed (generated cache dir): ${d}`);
  const { manifest, errors, excluded } = buildManifest(input);
  if (errors.length) {
    console.error(errors.join("\n"));
    return null;
  }
  return { m: manifest, excluded };
}

function runGenerate(): number {
  const b = build();
  if (!b) return 1;
  const { m } = b;
  const tmp = `${MANIFEST_FILE}.tmp-${process.pid}`;
  writeFileSync(tmp, serialiseManifest(m));
  renameSync(tmp, MANIFEST_FILE);
  report(m, b.excluded);
  return 0;
}

function runCheck(): number {
  const b = build();
  if (!b) return 1;
  const { m } = b;
  let committed = "";
  try {
    committed = readFileSync(MANIFEST_FILE, "utf8");
  } catch {
    console.error(`${MANIFEST_FILE} is missing — run: bun scripts/skill-manifest.ts generate`);
    return 1;
  }
  if (committed !== serialiseManifest(m)) {
    console.error("skills-manifest.json is stale (the tree, pack.json or vendor-lock.json changed) — run: bun scripts/skill-manifest.ts generate");
    return 1;
  }
  report(m, b.excluded);
  return 0;
}

if (import.meta.main) {
  const cmd = process.argv[2];
  if (cmd === "generate") process.exit(runGenerate());
  else if (cmd === "check") process.exit(runCheck());
  else {
    console.error(`usage: bun scripts/skill-manifest.ts generate|check   (lock: ${VENDOR_LOCK_FILE})`);
    process.exit(2);
  }
}
